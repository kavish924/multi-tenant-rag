package storage

import (
	"strconv"
	"strings"
)

// VectorLiteral formats a vector in pgvector's text form, "[x,y,...]", for
// a $n::vector parameter.
func VectorLiteral(v []float32) string {
	var b strings.Builder
	b.Grow(len(v) * 10)
	b.WriteByte('[')
	for i, x := range v {
		if i > 0 {
			b.WriteByte(',')
		}
		b.WriteString(strconv.FormatFloat(float64(x), 'g', -1, 32))
	}
	b.WriteByte(']')
	return b.String()
}
